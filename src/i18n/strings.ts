export const STRINGS: Record<Language, Strings> = { en, hi, gu };

export const strings = (lang: Language): Strings => STRINGS[lang] ?? en;

/** Fills "{name}" placeholders. */
export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

/** The phone's language if we have it, else English. */
export function deviceLanguage(): Language {
  try {
    const tag = Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase();
    if (tag.startsWith('hi')) return 'hi';
    if (tag.startsWith('gu')) return 'gu';
  } catch {
    // Fall through to English.
  }
  return 'en';
}
